/*
 * Build-time data generator.
 * Enumerates every multiset hand for the supported card ranges and ships the
 * result as js/data.js so the UI never has to block on a multi-second sweep.
 *
 *   node scripts/build-data.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const E = require(path.join(__dirname, '..', 'js', 'engine.js'));

const TARGET = 24;
const RANGES = [
  { key: '1-13', min: 1, max: 13, label: '扑克 A–K' },
  { key: '1-9', min: 1, max: 9, label: '数字 1–9' }
];

function sweep(min, max) {
  const hands = [];
  for (let a = min; a <= max; a++)
    for (let b = a; b <= max; b++)
      for (let c = b; c <= max; c++)
        for (let d = c; d <= max; d++) hands.push([a, b, c, d]);

  const dead = [];
  const live = [];
  const histogram = {}; // ideas -> how many hands
  let fractionOnly = 0; // solvable but every idea needs a fraction intermediate
  let richest = null, richestCount = -1;
  let singleIdea = null;

  for (const h of hands) {
    const r = E.solve(h, TARGET);
    const n = r.total;
    histogram[n] = (histogram[n] || 0) + 1;
    if (n === 0) {
      dead.push(h);
      continue;
    }
    live.push({ hand: h, ideas: n, raw: r.rawTotal });
    if (n > richestCount) { richestCount = n; richest = h; }
    if (n === 1 && !singleIdea) singleIdea = h;
    if (r.solutions.every(s => s.fractionUsed)) fractionOnly++;
  }

  const deadWithGap = dead.map(h => {
    const ap = E.bestApprox(h, TARGET);
    return { hand: h, near: ap ? ap.valueText : null, diff: ap ? ap.diffText : null };
  });

  // closest-miss leaderboard: dead hands whose best try lands within 2 of target
  const nearMisses = deadWithGap
    .filter(d => d.diff && (d.diff === '1' || d.diff === '2'))
    .sort((x, y) => Number(x.diff) - Number(y.diff))
    .slice(0, 24);

  return {
    range: { key: `${min}-${max}`, min, max, label: min === 1 && max === 13 ? '扑克 A–K' : `数字 ${min}–${max}` },
    combos: hands.length,
    solvable: live.length,
    dead: dead.length,
    deadRate: dead.length / hands.length,
    fractionOnlyHands: fractionOnly,
    richest: { hand: richest, ideas: richestCount },
    hardestIdeaHand: singleIdea,
    histogram,
    deadHands: dead,
    nearMisses,
    // one representative dead hand per max-card, for quick "show me a dead deck"
    deadSample: dead.slice(0, 400)
  };
}

const out = { generatedFrom: 'scripts/build-data.js', target: TARGET, ranges: {} };
for (const r of RANGES) out.ranges[r.key] = sweep(r.min, r.max);

// human-readable digest so a reviewer can sanity-check the shipped numbers
for (const key of Object.keys(out.ranges)) {
  const s = out.ranges[key];
  console.log(`${key}: combos=${s.combos} solvable=${s.solvable} dead=${s.dead} (${(s.deadRate * 100).toFixed(2)}%) ` +
    `richest=${s.richest.hand.join(',')}→${s.richest.ideas} ideas, fractionOnly=${s.fractionOnlyHands}, nearMisses=${s.nearMisses.length}`);
}

const banner = '/* AUTO-GENERATED by scripts/build-data.js — do not hand-edit.\n' +
  ' * Precomputed 24-game landscape so the browser never blocks on a sweep. */\n';
const body = banner + '(function(g,f){var d=f();if(typeof module==="object"&&module.exports)module.exports=d;if(typeof window==="object")window.TwentyFourData=d;})(null,function(){\n' +
  '  return ' + JSON.stringify(out) + ';\n});\n';

fs.writeFileSync(path.join(__dirname, '..', 'js', 'data.js'), body, 'utf8');
console.log('wrote js/data.js (' + (body.length / 1024).toFixed(1) + ' KB)');
